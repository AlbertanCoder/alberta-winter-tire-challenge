/* Grip tables and the legacy 1-D stopping model, lifted verbatim from index.html (v1).
   They stay the source of truth for target ABS-average grip (brief 4.2); the v2 tire curves in
   tire-params.js (generated by scripts/calibrate.js) turn these targets into forces.
   Pure code: loads in the browser (window.WTGrip) and in Node (require). */
(function(root, factory){ if (typeof module === 'object' && module.exports) module.exports = factory(); else root.WTGrip = factory(); })(typeof self !== 'undefined' ? self : this, function(){
'use strict';
const G = 9.81;
const TIRE_KEYS = ['winter','allweather','allseason','summer'];
// μ at −10 °C, average ABS deceleration ÷ g. Packed snow and ice converted from Tire Rack's 2026 tests;
// others are estimates that keep the tested ratios. (index.html v1, unchanged)
const COND = {
  dry:{name:'Cold dry pavement', kind:'dry', mu:{winter:.83,allweather:.83,allseason:.83,summer:.75}, est:true},
  fresh:{name:'Fresh snow', kind:'snow', mu:{winter:.33,allweather:.30,allseason:.20,summer:.10}, est:true},
  packed:{name:'Packed snow', kind:'snow', mu:{winter:.36,allweather:.34,allseason:.25,summer:.14}},
  slush:{name:'Slush', kind:'slush', mu:{winter:.30,allweather:.27,allseason:.21,summer:.14}, est:true},
  black:{name:'Black ice', kind:'ice', mu:{winter:.16,allweather:.12,allseason:.10,summer:.075}, est:true},
  polished:{name:'Polished ice', kind:'ice', mu:{winter:.14,allweather:.105,allseason:.095,summer:.065}, est:true},
  gravel:{name:'Snowy gravel', kind:'snow', mu:{winter:.34,allweather:.31,allseason:.24,summer:.14}, abs:.8, est:true},
  glaze:{name:'Glaze ice (freezing rain)', kind:'ice', mu:{winter:.10,allweather:.08,allseason:.07,summer:.05}, est:true}
};
// Heavier vehicles slightly lower μ (index.html v1 VEH.f)
const VEH_F = {small:1.0, sedan:.99, suv:.98, bigsuv:.96, van:.97, pickup:.95, hd:.92};
const HARD = {winter:.001, allweather:.002, allseason:.004, summer:.01};
const TMUL = {
  ice:[[10,.5],[0,.65],[-5,.9],[-10,1],[-20,1.1],[-30,1.12],[-40,1.12]],
  snow:[[10,.75],[0,.8],[-5,.92],[-10,1],[-20,1.05],[-30,1.07],[-40,1.08]]
};
// Locked wheels (no ABS): sliding grip as a share of ABS grip (index.html v1 LOCK / lockEff)
const LOCK = {dry:.9, ice:.82, snow:.88, slush:.9};
// Tread wear (ADAC: snow braking 86% of new at 4 mm; 2 mm values extrapolated from Continental's wear test)
const TREAD = {new:{name:'New', snow:1, ice:1, dry:1}, half:{name:'Half worn (4 mm)', snow:.86, ice:.9, dry:1.01}, limit:{name:'Near the limit (2 mm)', snow:.75, ice:.85, dry:1.02}};

function interp(tbl, T){ if (T >= tbl[0][0]) return tbl[0][1]; for (let i = 1; i < tbl.length; i++){ const a = tbl[i-1], b = tbl[i]; if (T >= b[0]) return a[1] + (T-a[0])/(b[0]-a[0])*(b[1]-a[1]); } return tbl[tbl.length-1][1]; }

// Table with calibration fixes applied ({cond:{tire:mu}}), e.g. the all-season packed-snow correction.
function table(fixes){
  const t = JSON.parse(JSON.stringify(COND));
  if (fixes) for (const c in fixes) for (const k in fixes[c]) t[c].mu[k] = fixes[c][k];
  return t;
}

// Legacy functions bound to a table (index.html v1 code, with COND as a parameter)
function make(fixes){
  const C = table(fixes);
  function mu(tire, cond, T, vehicle){
    const c = C[cond], k = c.kind;
    const tf = k === 'ice' ? interp(TMUL.ice, T) : k === 'snow' ? interp(TMUL.snow, T) : 1;
    const p = HARD[tire], cf = Math.max(.5, 1 - p*Math.max(0, 7 - T))/(1 - p*17);
    return c.mu[tire]*tf*cf*VEH_F[vehicle];
  }
  const absEff = cond => C[cond].abs || 1;
  function lockEff(cond){ return cond === 'gravel' ? 1.02 : cond === 'fresh' ? .95 : LOCK[C[cond].kind]; }
  function decel(m, grade, cond, abs){ const th = Math.atan((grade || 0)/100); return G*(m*(abs === false ? lockEff(cond) : absEff(cond))*Math.cos(th) + Math.sin(th)); }
  function treadEff(tread, cond){ const t = TREAD[tread || 'new'], k = C[cond].kind; return k === 'dry' ? t.dry : k === 'ice' ? t.ice : t.snow; }
  function gripMu(tire, cond, T, vehicle, tread){ return mu(tire, cond, T, vehicle)*treadEff(tread, cond); }
  function condAt(sc, s){ if (sc.zones) for (const z of sc.zones) if (s >= z[0] && s < z[1]) return z[2]; return sc.cond; }
  function surfaceAt(sc, s, weather){ const c = condAt(sc, s), w = weather || 'clear'; if (w === 'frzrain') return 'glaze'; if (w === 'snow' && c === 'dry') return 'fresh'; return c; }
  function runTemp(sc, weather){ return weather === 'frzrain' ? Math.max(sc.T, -2) : sc.T; }
  // Legacy 1-D stopping run (index.html v1 stopRun, verbatim). The reference for calibration.
  function stopRun(tire, sc, s0, v, o){
    const T = runTemp(sc, o.weather), dt = .01; let s = s0 + v*(o.rt || 0), d = v*(o.rt || 0), hit = null;
    if (o.target != null && d >= o.target) hit = v;
    for (let i = 0; i < 300000 && v > 0; i++){
      const cond = surfaceAt(sc, s, o.weather), a = decel(gripMu(tire, cond, T, o.vehicle, o.tread), sc.grade, cond, o.abs !== false) + .05 + .0004*v*v;
      v -= a*dt; const ds = Math.max(0, v)*dt; s += ds; d += ds;
      if (hit == null && o.target != null && d >= o.target) hit = Math.max(0, v);
      if (d > 3000) return {dist:Infinity, hitV:hit == null ? v : hit};
    }
    return {dist:d, hitV:hit == null ? 0 : hit};
  }
  return {COND:C, mu, absEff, lockEff, decel, treadEff, gripMu, condAt, surfaceAt, runTemp, stopRun};
}

return {G, TIRE_KEYS, COND, VEH_F, HARD, TMUL, LOCK, TREAD, interp, table, make};
});
